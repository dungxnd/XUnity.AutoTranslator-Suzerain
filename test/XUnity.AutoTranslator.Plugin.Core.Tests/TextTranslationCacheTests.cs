      [Fact( DisplayName = "Changed_File_Reload_Is_Incremental_And_Prune_Preserves_Unknown_Lines" )]
      public void Changed_File_Reload_Is_Incremental_And_Prune_Preserves_Unknown_Lines()
      {
         var directory = Path.Combine( Path.GetTempPath(), "xuat-cache-" + Guid.NewGuid().ToString( "N" ) );
         Directory.CreateDirectory( directory );

         var main = Path.Combine( directory, "_AutoGeneratedTranslations.txt" );
         var other = Path.Combine( directory, "other.txt" );
         var regex = Path.Combine( directory, "regex.txt" );

         var previousTranslationsPath = Settings.TranslationsPath;
         var previousMainPath = Settings.AutoTranslationsFilePath;
         var previousSubstitutionPath = Settings.SubstitutionFilePath;
         var previousPreprocessorsPath = Settings.PreprocessorsFilePath;
         var previousPostprocessorsPath = Settings.PostprocessorsFilePath;
         var previousScoping = Settings.EnableTranslationScoping;
         var previousRichText = Settings.HandleRichText;
         var previousPartials = Settings.GeneratePartialTranslations;

         TextTranslationCache cache = null;
         try
         {
            Settings.TranslationsPath = directory;
            Settings.AutoTranslationsFilePath = main;
            Settings.SubstitutionFilePath = Path.Combine( directory, "_Substitutions.txt" );
            Settings.PreprocessorsFilePath = Path.Combine( directory, "_Preprocessors.txt" );
            Settings.PostprocessorsFilePath = Path.Combine( directory, "_Postprocessors.txt" );
            Settings.EnableTranslationScoping = false;
            Settings.HandleRichText = false;
            Settings.GeneratePartialTranslations = false;

            File.WriteAllText( main,
               "hello=world\r\n" +
               "keep=me\r\n" +
               "// comment\r\n" +
               "#set level 1\r\n" +
               "http:\\/\\/a\\/\\/b=url\r\n" );
            File.WriteAllText( other, "foo=bar\r\n" );
            File.WriteAllText( regex, "r:\"^hello$\"=Hi\r\n" );

            cache = new TextTranslationCache();

            TranslationFileReader.ResetReadCount();
            cache.LoadTranslationFiles();

            Assert.Equal( 3, TranslationFileReader.TotalFileReads );
            Assert.Equal( "world", Lookup( cache, "hello" ) );
            Assert.Equal( "bar", Lookup( cache, "foo" ) );

            TranslationFileReader.ResetReadCount();
            cache.LoadTranslationFiles();

            Assert.Equal( 0, TranslationFileReader.TotalFileReads );

            File.AppendAllText( other, "added=new\r\n" );
            File.SetLastWriteTimeUtc( other, DateTime.UtcNow.AddSeconds( 2 ) );

            TranslationFileReader.ResetReadCount();
            cache.LoadTranslationFiles();

            Assert.Equal( 1, TranslationFileReader.TotalFileReads );
            Assert.Equal( "new", Lookup( cache, "added" ) );

            cache.PruneMainTranslationFile();

            var pruned = File.ReadAllText( main );
            Assert.DoesNotContain( "hello=world", pruned );
            Assert.Contains( "keep=me", pruned );
            Assert.Contains( "// comment", pruned );
            Assert.Contains( "#set level 1", pruned );
            Assert.Contains( "http:\\/\\/a\\/\\/b=url", pruned );
         }
         finally
         {
            cache?.Dispose();

            Settings.TranslationsPath = previousTranslationsPath;
            Settings.AutoTranslationsFilePath = previousMainPath;
            Settings.SubstitutionFilePath = previousSubstitutionPath;
            Settings.PreprocessorsFilePath = previousPreprocessorsPath;
            Settings.PostprocessorsFilePath = previousPostprocessorsPath;
            Settings.EnableTranslationScoping = previousScoping;
            Settings.HandleRichText = previousRichText;
            Settings.GeneratePartialTranslations = previousPartials;

            Directory.Delete( directory, true );
         }
      }

      [Fact( DisplayName = "Wrapper_Variants_Reuse_Cached_Translations" )]
      public void Wrapper_Variants_Reuse_Cached_Translations()
      {
         var directory = Path.Combine( Path.GetTempPath(), "xuat-cache-" + Guid.NewGuid().ToString( "N" ) );
         Directory.CreateDirectory( directory );

         var main = Path.Combine( directory, "_AutoGeneratedTranslations.txt" );

         var previousTranslationsPath = Settings.TranslationsPath;
         var previousMainPath = Settings.AutoTranslationsFilePath;
         var previousSubstitutionPath = Settings.SubstitutionFilePath;
         var previousPreprocessorsPath = Settings.PreprocessorsFilePath;
         var previousPostprocessorsPath = Settings.PostprocessorsFilePath;
         var previousScoping = Settings.EnableTranslationScoping;
         var previousRichText = Settings.HandleRichText;
         var previousPartials = Settings.GeneratePartialTranslations;
         var previousReload = Settings.ReloadTranslationsOnFileChange;
         var previousTemplateAllNumbers = Settings.TemplateAllNumberAway;

         TextTranslationCache cache = null;
         try
         {
            Settings.TranslationsPath = directory;
            Settings.AutoTranslationsFilePath = main;
            Settings.SubstitutionFilePath = Path.Combine( directory, "_Substitutions.txt" );
            Settings.PreprocessorsFilePath = Path.Combine( directory, "_Preprocessors.txt" );
            Settings.PostprocessorsFilePath = Path.Combine( directory, "_Postprocessors.txt" );
            Settings.EnableTranslationScoping = false;
            Settings.HandleRichText = false;
            Settings.GeneratePartialTranslations = false;
            Settings.ReloadTranslationsOnFileChange = false;
            Settings.TemplateAllNumberAway = false;

            File.WriteAllText( main,
               "Hello brother=Chào người anh em\r\n" +
               "1. Good morning=1. Chào buổi sáng\r\n" +
               "Quoted only=\"Đã dịch\"\r\n" );

            cache = new TextTranslationCache();
            cache.LoadTranslationFiles();

            Assert.Equal( "Chào người anh em", Lookup( cache, "Hello brother" ) );
            Assert.Equal( "\"Chào người anh em\"", Lookup( cache, "\"Hello brother\"" ) );
            Assert.Equal( "<Chào người anh em>", Lookup( cache, "<Hello brother>" ) );
            Assert.Equal( "1. \"Chào người anh em\"", Lookup( cache, "1. \"Hello brother\"" ) );
            Assert.Equal( "\"1. Chào người anh em\"", Lookup( cache, "\"1. Hello brother\"" ) );

            Assert.Equal( "Chào buổi sáng", Lookup( cache, "Good morning" ) );
            Assert.Equal( "\"Chào buổi sáng\"", Lookup( cache, "\"Good morning\"" ) );
            Assert.Equal( "<Chào buổi sáng>", Lookup( cache, "<Good morning>" ) );
            Assert.Equal( "1. \"Chào buổi sáng\"", Lookup( cache, "1. \"Good morning\"" ) );
            Assert.Equal( "\"1. Chào buổi sáng\"", Lookup( cache, "\"1. Good morning\"" ) );

            Assert.Equal( "\"Đã dịch\"", Lookup( cache, "Quoted only" ) );
            Assert.Equal( "\"Đã dịch\"", Lookup( cache, "\"Quoted only\"" ) );

            Assert.False( cache.IsTranslatable( "\"Chào người anh em\"", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "1. Chào buổi sáng", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "\"Chào buổi sáng\"", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "<Chào buổi sáng>", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "\"1. Chào buổi sáng\"", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "\"Đã dịch\"", false, TranslationScopes.None ) );
            Assert.False( cache.IsTranslatable( "Đã dịch", false, TranslationScopes.None ) );
         }
         finally
         {
            cache?.Dispose();

            Settings.TranslationsPath = previousTranslationsPath;
            Settings.AutoTranslationsFilePath = previousMainPath;
            Settings.SubstitutionFilePath = previousSubstitutionPath;
            Settings.PreprocessorsFilePath = previousPreprocessorsPath;
            Settings.PostprocessorsFilePath = previousPostprocessorsPath;
            Settings.EnableTranslationScoping = previousScoping;
            Settings.HandleRichText = previousRichText;
            Settings.GeneratePartialTranslations = previousPartials;
            Settings.ReloadTranslationsOnFileChange = previousReload;
            Settings.TemplateAllNumberAway = previousTemplateAllNumbers;

            Directory.Delete( directory, true );
         }
      }

      private static string Lookup( TextTranslationCache cache, string text )
      {
         var key = new UntranslatedText( text, false, true, false, false, false );
         cache.TryGetTranslation( key, false, false, TranslationScopes.None, out var value );
         return value;
      }
   }
